<div class="compare-pair">
<article class="compare-choice">
<div class="compare-choice-head"><span class="choice-kicker">Escolha A</span><span class="e5-badge">CORE 2024</span></div>
<h4>Conjurador de Guerra (War Caster)</h4>
<p class="choice-summary">Ajuda a manter Concentração, permite componentes somáticos com mãos ocupadas e magia como Reação.</p>
<div class="choice-rule"><strong>Escolha quando:</strong> mãos ocupadas, magia como Reação ou o +1 em Carisma têm peso real para a build.</div>
<div class="choice-meta"><strong>Pré-requisito:</strong> Level 4+, Spellcasting or Pact Magic Feature</div>
<div class="choice-meta"><strong>Trade-off:</strong> Mente Mística já concede Vantagem nos mesmos salvamentos de Concentração; para Bruxo, o diferencial real passa a ser +1 Carisma, magia reativa e componentes somáticos com mãos ocupadas.</div>
</article>
<article class="compare-choice">
<div class="compare-choice-head"><span class="choice-kicker">Escolha B</span><span class="e5-badge">CORE 2024</span></div>
<h4>Resiliente (Resilient) — CON</h4>
<p class="choice-summary">Aumenta um atributo e concede proficiência no salvamento desse atributo, se ainda não houver.</p>
<div class="choice-rule"><strong>Escolha quando:</strong> você quer proficiência em salvamentos de Constituição, proteção geral de CON e escala com bônus de proficiência.</div>
<div class="choice-meta"><strong>Pré-requisito:</strong> Level 4+</div>
<div class="choice-meta"><strong>Trade-off:</strong> O uso mais forte costuma ser Constituição; o +1 rende mais quando fecha um valor ímpar. Não substitui a Vantagem de Mente Mística, mas se acumula muito bem com ela.</div>
</article>
</div>
