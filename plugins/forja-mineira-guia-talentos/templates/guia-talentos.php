<h4>Resistente a Magia (Spell Resistant)</h4>
<p class="choice-summary">Escolhe Resistência a Necrótico, Psíquico, Radiante ou Trovejante. PB vezes/LR, ao falhar salvamento contra magia/efeito mágico, soma 1d6 e pode transformar em sucesso.</p>
<div class="choice-rule"><strong>Escolha quando:</strong> a campanha tem muita magia, CON está ímpar ou defesa contra efeitos mágicos é o gargalo.</div>
<div class="choice-meta"><strong>Pré-requisito:</strong> Level 4+</div>
<div class="choice-meta"><strong>Trade-off:</strong> Não aumenta Carisma; resistência depende do tipo escolhido e o +1d6 é limitado.</div>
